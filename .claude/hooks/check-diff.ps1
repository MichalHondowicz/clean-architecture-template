# Verifier script, not a hook: checks a ticket's commit range for changes the implementer may not make,
# whatever tool made them (writes through Bash never reach the PreToolUse guard).
# Usage, inside the repository: pwsh -File check-diff.ps1 -Base <rev> [-Head <rev>]
# Prints {"violations":[{"kind","path","detail"}],"testsToReview":[...]}; exits 1 when there are violations,
# 2 when the range cannot be checked.

param(
    [Parameter(Mandatory)] [string]$Base,
    [string]$Head = 'HEAD'
)

$ErrorActionPreference = 'Stop'
# git prints paths and file contents as UTF-8; without this a BOM or a non-ASCII path decodes wrongly.
[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
. (Join-Path $PSScriptRoot 'dod-common.ps1')

$root = Find-DodRoot (Get-Location).Path
if (-not $root) {
    [Console]::Error.WriteLine("No $DodRelativePath at or above $(Get-Location).")
    exit 2
}

# Added lines that switch analyzers off or downgrade them (AGENTS.md: never add a suppression). They count only in
# code and build files; documents may quote them, as tickets and AGENTS.md do.
$codeOrBuildFile = '\.(cs|csproj|props|targets)$'
$suppressionPatterns = @(
    '#pragma\s+warning\s+disable'
    'SuppressMessage'
    '<NoWarn[\s>]'
    '<WarningsNotAsErrors[\s>]'
    '<(CodeAnalysis)?TreatWarningsAsErrors[^>]*>\s*false'
    '<RunAnalyzers[^>]*>\s*false'
    '<EnableNETAnalyzers[^>]*>\s*false'
    '<Analysis(Mode|Level)[\s>]'
)
# In analyzer config files any severity line is a suppression candidate.
$analyzerConfigFile = '(^|/)\.editorconfig$|\.globalconfig$'

function Find-Suppression([string]$path, [string]$addedLine) {
    if ($path -match $analyzerConfigFile -and $addedLine -match 'severity\s*=') {
        return $addedLine.Trim()
    }
    if ($path -match $codeOrBuildFile) {
        foreach ($pattern in $suppressionPatterns) {
            if ($addedLine -match $pattern) {
                return $addedLine.Trim()
            }
        }
    }
    $null
}

function Invoke-Git {
    $output = & git -c core.quotePath=false @args
    if ($LASTEXITCODE -ne 0) {
        [Console]::Error.WriteLine("git $args failed.")
        exit 2
    }
    $output
}

# Tool-generated files (first line `// <auto-generated />`, e.g. EF migrations, which keep their BOM) are exempt.
$generated = @{}
function Test-Generated([string]$path) {
    if (-not $generated.ContainsKey($path)) {
        $firstLine = "$(@(Invoke-Git show "${Head}:$path")[0])".TrimStart([char]0xFEFF)
        $generated[$path] = $firstLine.StartsWith('// <auto-generated')
    }
    $generated[$path]
}

Push-Location $root
try {
    # The protected list comes from the base revision: the range under check may itself have weakened the DoD file.
    $baseDod = & git show "${Base}:$DodRelativePath" 2>$null
    $dod = $LASTEXITCODE -eq 0 ? ($baseDod -join "`n" | ConvertFrom-Json) : (Read-Dod $root)

    $violations = [Collections.Generic.List[object]]::new()
    $testsToReview = [Collections.Generic.List[string]]::new()

    foreach ($line in (Invoke-Git diff --no-renames --name-status $Base $Head)) {
        $status, $path = $line -split "`t", 2
        $pattern = Find-ProtectedPattern $path $dod.protectedPaths
        if ($pattern) {
            $violations.Add([ordered]@{ kind = 'protected-path'; path = $path; detail = "matches '$pattern'" })
        }
        # An existing test that changed or vanished is not a violation by itself; the verifier judges it.
        if ($status -in 'M', 'D' -and $path -like 'tests/*.cs') {
            $testsToReview.Add($path)
        }
    }

    # Only changed lines count (-U0, no context), so suppressions that were already there are not reported.
    # A file's header runs from `diff --git` to `+++`; its `--- a/...` line is not a removed line.
    $file = $null
    $inHeader = $false
    foreach ($line in (Invoke-Git diff --no-renames --no-color -U0 $Base $Head)) {
        if ($line.StartsWith('diff --git ')) {
            $inHeader = $true
            continue
        }
        if ($inHeader) {
            if ($line.StartsWith('+++ ')) {
                # git appends a TAB to header paths that contain a space.
                $file = $line -eq '+++ /dev/null' ? $null : $line.Substring('+++ b/'.Length).TrimEnd("`t")
                $inHeader = $false
            }
            continue
        }
        if ($file -and $line.StartsWith('+')) {
            $suppression = Find-Suppression $file $line.Substring(1)
            if ($suppression -and -not (Test-Generated $file)) {
                $violations.Add([ordered]@{ kind = 'suppression'; path = $file; detail = $suppression })
            }
        }
        # A project dropped from the solution drops its tests from the DoD's test run.
        if ($file -match '\.slnx?$' -and $line.StartsWith('-') -and $line -match 'Project[\s(]') {
            $violations.Add([ordered]@{ kind = 'solution-project-removed'; path = $file; detail = $line.Substring(1).Trim() })
        }
    }

    [ordered]@{ violations = @($violations); testsToReview = @($testsToReview) } | ConvertTo-Json -Depth 5 -Compress
    exit ($violations.Count -gt 0 ? 1 : 0)
}
finally {
    Pop-Location
}
